// Writes docs/results.json: every number the README and the demo page quote.
//   npm run evaluate
import fs from "node:fs";
import path from "node:path";
import { candidates } from "../candidates/index.js";
import { scoreAll, reportPair, subsetIndices } from "../src/pipeline.js";
import { summarize } from "../src/evaluate.js";
import { judgeVersusHuman } from "../src/ratings.js";
import { measureFlakiness } from "../src/flakiness.js";
import { sliceKeys } from "../src/testset.js";
import { loadAll, ROOT } from "./load.mjs";

export async function buildResults() {
  const { cases, ratings, config } = loadAll();
  const { scored, outputs } = await scoreAll(candidates, cases);
  const ids = Object.keys(candidates);
  const pairs = [];
  for (let i = 0; i < ids.length; i++) for (let j = i + 1; j < ids.length; j++) pairs.push({ base: ids[i], candidate: ids[j], ...reportPair(scored, ids[i], ids[j], config) });

  const replyOf = (v, id) => outputs[v][cases.findIndex((c) => c.id === id)]?.reply;
  const agreementFor = (lenient) => {
    const r = judgeVersusHuman(ratings, cases, replyOf, { lenient });
    return { n: r.n, agreement: r.agreement, kappa: r.kappa, table: r.table, stale: r.stale.length };
  };

  const flakiness = {};
  for (const id of ids) {
    const f = await measureFlakiness(candidates[id], cases, { ...config.flakiness, seed: config.seed });
    const { perCase, ...rest } = f;
    flakiness[id] = { ...rest, unstableIds: perCase.filter((c) => c.unstable).map((c) => c.id) };
  }

  const shrink = [];
  for (const keep of [20, 40, 60, 100, 140, cases.length]) {
    const r = reportPair(scored, "v2", "v3", config, subsetIndices(cases.length, keep, config.seed));
    shrink.push({ keep, accuracyCiWidth: r.candidate.intentAccuracy.hi - r.candidate.intentAccuracy.lo, minDetectableDifference: r.comparison.minDetectableDifference, verdict: r.gate.headline });
  }

  const counts = {};
  for (const c of cases) for (const k of sliceKeys(c)) counts[k] = (counts[k] ?? 0) + 1;
  return {
    note: "Generated by `npm run evaluate`. Candidates are deterministic stand-ins for model versions; ratings were written for the demo.",
    seed: config.seed,
    bootstrapIterations: config.bootstrapIterations,
    testSet: { cases: cases.length, slices: counts },
    ratings: { count: ratings.length },
    gateConfig: config.gate,
    shipped: config.shipped,
    versions: Object.fromEntries(ids.map((id) => [id, summarize(scored[id], { seed: config.seed, iterations: config.bootstrapIterations })])),
    pairs: pairs.map((p) => ({ base: p.base, candidate: p.candidate, comparison: p.comparison, gate: p.gate })),
    judge: { strict: agreementFor(false), lenient: agreementFor(true) },
    flakiness,
    shrink,
  };
}


const round = (_, v) => (typeof v === "number" ? Math.round(v * 1e4) / 1e4 : v);

if (import.meta.url === `file://${process.argv[1]}`) {
  const results = await buildResults();
  fs.writeFileSync(path.join(ROOT, "docs/results.json"), JSON.stringify(results, round, 2) + "\n");
  console.log("wrote docs/results.json");
}
